#!/usr/bin/env python3
"""Generate src/theme/nvchad.rs from the Neovim-resolved base46 dump.

Usage: python3 scripts/gen-nvchad-themes.py [path/to/base46.json]
The default input is the dump kept by ~/Projects/nvchad-themes-vscode.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = Path.home() / "Projects/nvchad-themes-vscode/data/base46.json"
OUTPUT = ROOT / "src/theme/nvchad.rs"

# Field name in Palette -> highlight group resolved by Neovim.
GROUPS = {
    "normal": "Normal",
    "float": "NormalFloat",
    "float_border": "FloatBorder",
    "float_title": "FloatTitle",
    "separator": "WinSeparator",
    "cursor_line": "CursorLine",
    "line_nr": "LineNr",
    "cursor_line_nr": "CursorLineNr",
    "visual": "Visual",
    "comment": "Comment",
    "string": "String",
    "key": "@property",
    "operator": "@operator",
    "title": "Title",
    "directory": "Directory",
    "error": "DiagnosticError",
    "warn": "DiagnosticWarn",
    "info": "DiagnosticInfo",
    "ok": "MoreMsg",
    "search": "Search",
    "pmenu_sel": "PmenuSel",
    "statusline": "StatusLine",
    "empty_space": "St_EmptySpace",
    "file": "St_file",
    "file_sep": "St_file_sep",
    "git": "St_gitIcons",
    "lsp": "St_Lsp",
    "cwd_sep": "St_cwd_sep",
    "cwd_icon": "St_cwd_icon",
    "cwd_text": "St_cwd_text",
    "pos_sep": "St_pos_sep",
    "pos_icon": "St_pos_icon",
    "pos_text": "St_pos_text",
}
MODES = ["Normal", "Insert", "Command", "Terminal", "NTerminal", "Confirm"]

# base46/term.lua: vim.g.terminal_color_0..15 come from these base_16 slots.
TERM = [
    "base01", "base08", "base0B", "base0A", "base0D", "base0E", "base0C", "base05",
    "base03", "base08", "base0B", "base0A", "base0D", "base0E", "base0C", "base07",
]


def color(value):
    return "N" if not value else f"0x{value.lstrip('#').lower()}"


def hl(group):
    group = group or {}
    bold = "true" if group.get("bold") else "false"
    return f"hl({color(group.get('fg'))}, {color(group.get('bg'))}, {bold})"


def main():
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_INPUT
    data = json.loads(source.read_text())
    themes = data["themes"]
    commit = data.get("source", {}).get("commit", "unknown")
    out = [
        f"// Generated by scripts/gen-nvchad-themes.py from base46 @{commit}; do not edit by hand.",
        "use super::{N, Palette, hl};",
        "",
        "pub const THEMES: &[Palette] = &[",
    ]
    for name in sorted(themes):
        theme = themes[name]
        groups = theme["hl"]
        out.append("    Palette {")
        out.append(f"        name: {json.dumps(name)},")
        out.append(f"        light: {'true' if theme['type'] == 'light' else 'false'},")
        for field, group in GROUPS.items():
            out.append(f"        {field}: {hl(groups.get(group))},")
        modes = ", ".join(hl(groups.get(f"St_{m}Mode")) for m in MODES)
        seps = ", ".join(hl(groups.get(f"St_{m}ModeSep")) for m in MODES)
        out.append(f"        modes: [{modes}],")
        out.append(f"        mode_seps: [{seps}],")
        ansi = ", ".join(color(theme["base_16"][slot]) for slot in TERM)
        out.append(f"        ansi: [{ansi}],")
        out.append("    },")
    out.append("];")
    OUTPUT.write_text("\n".join(out) + "\n")
    print(f"Wrote {len(themes)} themes to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
