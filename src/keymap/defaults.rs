use super::{Action, Context};

pub struct Def {
    pub ctx: Context,
    pub action: Action,
    pub name: &'static str,
    pub keys: &'static [&'static str],
    pub desc: &'static str,
}

const fn def(
    ctx: Context,
    action: Action,
    name: &'static str,
    keys: &'static [&'static str],
    desc: &'static str,
) -> Def {
    Def {
        ctx,
        action,
        name,
        keys,
        desc,
    }
}

